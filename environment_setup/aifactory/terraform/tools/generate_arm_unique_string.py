#!/usr/bin/env python3
"""Generate modules/arm-unique-string/main.tf: ARM uniqueString() in plain Terraform.

ARM's uniqueString(a, b, ...) is MurmurHash64A of "a-b-..." (UTF-8, seed 0) written as
13 base32 characters. Terraform has no bitwise operators, loops with state or ord(),
so this generator unrolls the hash into locals that use exact integer arithmetic
(Terraform numbers are arbitrary precision): XOR is done bit by bit, rotation with
multiplication and division, and characters become bytes through a printable ASCII map.

azapi's provider::azapi::unique_string() is not used: in v2.13.0 it differs from ARM
whenever the input length modulo 8 is 5, 6 or 7 and the tail word is negative after
multiplication (it takes the absolute value instead of the two's-complement bits).
The test suite checks this module against the Bicep compiler's own evaluation.

Usage: python generate_arm_unique_string.py [--check]
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

MAX_BYTES = 256
ROUNDS = MAX_BYTES // 8
TARGET = Path(__file__).resolve().parent.parent / "modules" / "arm-unique-string" / "main.tf"
M32 = "4294967296"


def xor(a: str, b: str) -> str:
    return f"sum([for j in range(32) : ((floor(({a}) / pow(2, j)) + floor(({b}) / pow(2, j))) % 2) * pow(2, j)])"


def mul(a: str, c: str) -> str:
    return f"(({a}) * {c}) % {M32}"


def rotl(a: str, r: int) -> str:
    return f"((({a}) * {2 ** r}) % {M32} + floor(({a}) / {2 ** (32 - r)}))"


def word(start: str) -> str:
    return " + ".join(f"local.bytes[{start} + {i}] * {256 ** i}" for i in range(4))


def render() -> str:
    out: list[str] = []
    w = out.append
    w("# GENERATED by ../../tools/generate_arm_unique_string.py - do not edit by hand.")
    w("# ARM uniqueString(): MurmurHash64A (seed 0) of the inputs joined with \"-\", as 13 base32 characters.")
    w("")
    w("locals {")
    w("  text  = join(\"-\", var.values)")
    w("  chars = regexall(\".\", local.text)")
    w("  ascii = {")
    for code in range(32, 127):
        key = chr(code).replace("\\", "\\\\").replace('"', '\\"')
        w(f'    "{key}" = {code}')
    w("  }")
    w("  codes = [for c in local.chars : local.ascii[c]]")
    w("  n     = length(local.codes)")
    w(f"  bytes = concat(local.codes, [for i in range({MAX_BYTES + 8} - local.n) : 0])")
    w("  full  = floor(local.n / 8)")
    w("  tail  = local.n % 8")
    w("")
    w("  r0_h1 = 0")
    w("  r0_h2 = 0")
    for i in range(1, ROUNDS + 1):
        p = i - 1
        base = str(p * 8)
        w("")
        w(f"  # round {i}: bytes {p * 8}-{p * 8 + 7}")
        w(f"  r{i}_k1 = {rotl(mul(word(base), '597399067'), 15)}")
        w(f"  r{i}_k1m = {mul(f'local.r{i}_k1', '2869860233')}")
        w(f"  r{i}_h1a = {rotl(xor(f'local.r{p}_h1', f'local.r{i}_k1m'), 19)}")
        w(f"  r{i}_h1b = ((local.r{i}_h1a + local.r{p}_h2) % {M32} * 5 + 1444728091) % {M32}")
        w(f"  r{i}_k3 = {rotl(mul(word(str(p * 8 + 4)), '2869860233'), 17)}")
        w(f"  r{i}_k3m = {mul(f'local.r{i}_k3', '597399067')}")
        w(f"  r{i}_h2a = {rotl(xor(f'local.r{p}_h2', f'local.r{i}_k3m'), 13)}")
        w(f"  r{i}_h2b = ((local.r{i}_h2a + local.r{i}_h1b) % {M32} * 5 + 197830471) % {M32}")
        w(f"  r{i}_h1 = local.full >= {i} ? local.r{i}_h1b : local.r{p}_h1")
        w(f"  r{i}_h2 = local.full >= {i} ? local.r{i}_h2b : local.r{p}_h2")
    last = ROUNDS
    w("")
    w("  # tail: the last 1-7 bytes")
    w("  t0 = local.full * 8")
    w("  k2 = sum([for i in range(4) : i < local.tail ? local.bytes[local.t0 + i] * pow(256, i) : 0])")
    w(f"  k2r = {mul(rotl(mul('local.k2', '597399067'), 15), '2869860233')}")
    w(f"  t_h1 = local.tail > 0 ? {xor(f'local.r{last}_h1', 'local.k2r')} : local.r{last}_h1")
    w("  k4 = sum([for i in range(3) : i + 4 < local.tail ? local.bytes[local.t0 + 4 + i] * pow(256, i) : 0])")
    w("  # int32 multiply by -1425107063, then reinterpret the 32 bits as unsigned (two's complement)")
    w(f"  k4u = ((local.k4 * -1425107063) % {M32} + {M32}) % {M32}")
    w(f"  k4r = {mul(rotl('local.k4u', 17), '597399067')}")
    w(f"  t_h2 = local.tail > 4 ? {xor(f'local.r{last}_h2', 'local.k4r')} : local.r{last}_h2")
    w("")
    w("  # finalization")
    w(f"  f_h1a = {xor('local.t_h1', 'local.n')}")
    w(f"  f_h2a = {xor('local.t_h2', 'local.n')}")
    w(f"  f_h1b = (local.f_h1a + local.f_h2a) % {M32}")
    w(f"  f_h2b = (local.f_h2a + local.f_h1b) % {M32}")
    for h in ("h1", "h2"):
        src = f"local.f_{h}b"
        w(f"  m_{h}1 = {mul(xor(src, f'floor({src} / 65536)'), '2246822507')}")
        w(f"  m_{h}2 = {mul(xor(f'local.m_{h}1', f'floor(local.m_{h}1 / 8192)'), '3266489909')}")
        w(f"  m_{h}3 = {xor(f'local.m_{h}2', f'floor(local.m_{h}2 / 65536)')}")
    w(f"  o_h1 = (local.m_h13 + local.m_h23) % {M32}")
    w(f"  o_h2 = (local.m_h23 + local.o_h1) % {M32}")
    w("  hash = local.o_h2 * 4294967296 + local.o_h1")
    w("  base32 = \"abcdefghijklmnopqrstuvwxyz234567\"")
    w("  value = join(\"\", concat(")
    w("    [for i in range(12) : substr(local.base32, floor(local.hash / pow(2, 59 - 5 * i)) % 32, 1)],")
    w("    [substr(local.base32, (local.hash * 2) % 32, 1)],")
    w("  ))")
    w("}")
    w("")
    return "\n".join(out)


def align(text: str) -> str:
    """Align `=` of consecutive single-line attributes at the same indentation, as `terraform fmt` does."""
    import re

    lines = text.split("\n")
    pattern = re.compile(r'^(\s+)("(?:[^"\\]|\\.)*"|[A-Za-z_][\w]*) = (.*)$')

    def balanced(rest: str) -> bool:
        return all(rest.count(a) == rest.count(b) for a, b in ("()", "[]", "{}"))

    out, group = [], []

    def flush():
        if group:
            width = max(len(key) for _, key, _ in group)
            out.extend(f"{indent}{key.ljust(width)} = {rest}" for indent, key, rest in group)
            group.clear()

    for line in lines:
        match = pattern.match(line)
        if match and balanced(match.group(3)) and (not group or group[0][0] == match.group(1)):
            group.append(match.groups())
            continue
        flush()
        if match and balanced(match.group(3)):
            group.append(match.groups())
        else:
            out.append(line)
    flush()
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if main.tf is not up to date")
    args = parser.parse_args(argv)
    text = align(render())
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(f"{TARGET} is out of date; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    TARGET.write_bytes(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
