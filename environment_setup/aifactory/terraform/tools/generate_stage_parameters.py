#!/usr/bin/env python3
"""Generate the `parameters` variable of each stage module from the compiled Bicep entry file.

Every stage module (modules/stage-11-rg-common, stage-12-network-common, stage-13-rg-level) takes one object
variable `parameters` whose attributes are the Bicep entry file's parameters: same names, same types, same
defaults, same allowed values. Generating it from `bicep build` output keeps the two parameter lists identical
by construction; the test suite re-runs this generator with --check.

Two kinds of Bicep parameter are not attributes of `parameters`:
* @secure() parameters (adminPassword): a separate sensitive variable, so names derived from `parameters`
  are not marked sensitive.
* parameters whose default is a runtime expression (keyVaultSecretExpiry = utcNow() + 1 year): a separate
  required variable; the workflow computes the value.

Usage: python generate_stage_parameters.py [--bicep PATH] [--check]
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

TERRAFORM = Path(__file__).resolve().parent.parent
BICEP_MAIN = TERRAFORM.parent / "bicep" / "esml-common" / "main"
STAGES = {
    "stage-11-rg-common": "11-rgCommon.bicep",
    "stage-12-network-common": "12-networkCommon.bicep",
    "stage-13-rg-level": "13-rgLevel.bicep",
}
SEPARATE = {
    "adminPassword": "admin_password",
    "keyVaultSecretExpiry": "key_vault_secret_expiry",
}
TYPES = {"string": "string", "bool": "bool", "int": "number", "object": "any", "array": "any"}


def compile_template(bicep: str, path: Path) -> dict:
    result = subprocess.run([bicep, "build", str(path), "--stdout", "--no-restore"],
                            capture_output=True, text=True, encoding="utf-8", timeout=600, check=False)
    if result.returncode:
        raise SystemExit(f"bicep build {path.name} failed:\n{result.stderr}")
    return json.loads(result.stdout)


def hcl(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value).replace("${", "$${").replace("%{", "%%{")
    if isinstance(value, list):
        return "[" + ", ".join(hcl(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{key} = {hcl(item)}" for key, item in value.items()) + " }"
    raise TypeError(value)


def render(entry: str, template: dict) -> str:
    out = [
        f"# GENERATED by ../../tools/generate_stage_parameters.py from bicep/esml-common/main/{entry} - do not edit.",
        f"# The attributes are the Bicep parameters of {entry}: same names, types, defaults and allowed values.",
        "",
        'variable "parameters" {',
        f'  description = "Parameters of {entry}, keyed by their Bicep names."',
        "  type = object({",
    ]
    validations = []
    width = max(len(name) for name in template["parameters"] if name not in SEPARATE)
    for name, declared in template["parameters"].items():
        if name in SEPARATE:
            continue
        kind = declared["type"].lower()
        if kind == "securestring":
            raise SystemExit(f"{entry}: @secure() parameter {name} needs an entry in SEPARATE")
        tf_type = TYPES[kind]
        default = declared.get("defaultValue")
        if isinstance(default, str) and default.startswith("[") and default.endswith("]"):
            raise SystemExit(f"{entry}: parameter {name} has an expression default; add it to SEPARATE")
        if "defaultValue" in declared:
            out.append(f"    {name.ljust(width)} = optional({tf_type}, {hcl(default)})")
        else:
            out.append(f"    {name.ljust(width)} = {tf_type}")
        if "allowedValues" in declared:
            validations.append((name, declared["allowedValues"]))
    out.append("  })")
    for name, allowed in validations:
        listed = ", ".join(str(item) for item in allowed)
        out += [
            "",
            "  validation {",
            f"    condition     = contains({hcl(allowed)}, var.parameters.{name})",
            f'    error_message = "parameters.{name} must be one of: {listed}."',
            "  }",
        ]
    out += ["}", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--bicep", default=os.environ.get("BICEP") or shutil.which("bicep") or "bicep")
    parser.add_argument("--check", action="store_true", help="fail if a parameters.tf is not up to date")
    args = parser.parse_args(argv)
    stale = []
    for module, entry in STAGES.items():
        text = render(entry, compile_template(args.bicep, BICEP_MAIN / entry))
        target = TERRAFORM / "modules" / module / "parameters.tf"
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                stale.append(str(target))
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))
    if stale:
        print("Out of date (run generate_stage_parameters.py):\n" + "\n".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
