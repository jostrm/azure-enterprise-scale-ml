"""Deterministic synthetic tabular sources for scenarios that must not use third-party data.

Generators use only ``random.Random(seed).random()``, whose sequence Python keeps stable for a
given seed, so the same scenario reproduces byte-identical files on every supported platform.
Outputs are written once with hash-pinned provenance and are never silently replaced.
"""

import csv
import hashlib
import io
import math
import random
from pathlib import Path

from .config import load_json, write_json

TELCO_COLUMNS = (
    "customerID", "gender", "SeniorCitizen", "Partner", "Dependents", "tenure", "PhoneService",
    "InternetService", "Contract", "PaperlessBilling", "PaymentMethod", "MonthlyCharges", "TotalCharges", "Churn",
)
LICENSE = "Synthetic data generated by ml_model_factory.synthetic; no third-party data or license review"


def _pick(rng: random.Random, options) -> str:
    total = sum(weight for _, weight in options)
    point = rng.random() * total
    for value, weight in options:
        point -= weight
        if point < 0:
            return value
    return options[-1][0]


def _yes(rng: random.Random, probability: float) -> str:
    return "Yes" if rng.random() < probability else "No"


def _telco(rng: random.Random, index: int, prefix: str) -> dict:
    """One customer with a logistic churn signal similar in shape to public telco churn examples."""
    gender = _pick(rng, (("Female", 1), ("Male", 1)))
    senior = 1 if rng.random() < 0.16 else 0
    partner = _yes(rng, 0.48)
    dependents = _yes(rng, 0.45 if partner == "Yes" else 0.12)
    segment = rng.random()
    tenure = (int(rng.random() * 13) if segment < 0.30 else
              60 + int(rng.random() * 13) if segment < 0.55 else 13 + int(rng.random() * 47))
    weights = ((0.78, 0.15, 0.07) if tenure < 12 else (0.52, 0.28, 0.20) if tenure < 36 else (0.22, 0.33, 0.45))
    contract = _pick(rng, tuple(zip(("Month-to-month", "One year", "Two year"), weights)))
    phone = _yes(rng, 0.90)
    internet = _pick(rng, (("Fiber optic", 44), ("DSL", 34), ("No", 22)))
    if phone == "No" and internet == "No":
        phone = "Yes"
    paperless = _yes(rng, 0.59)
    payment = _pick(rng, (("Electronic check", 34), ("Mailed check", 23),
                          ("Bank transfer (automatic)", 22), ("Credit card (automatic)", 21)))
    spread = rng.random()
    monthly = {"No": 19.0 + 6.0 * spread, "DSL": 45.0 + 25.0 * spread, "Fiber optic": 70.0 + 45.0 * spread}[internet]
    monthly = round(min(120.0, max(18.25, monthly + (5.0 if phone == "Yes" and internet != "No" else 0.0))), 2)
    total = "" if tenure == 0 else f"{tenure * monthly * (0.97 + 0.06 * rng.random()):.2f}"
    score = (-1.40 + 1.25 * (contract == "Month-to-month") - 0.9 * (contract == "Two year") - 0.035 * tenure
             + 0.75 * (internet == "Fiber optic") - 0.45 * (internet == "No")
             + 0.5 * (payment == "Electronic check") + 0.3 * senior + 0.25 * (paperless == "Yes")
             - 0.2 * (partner == "Yes") - 0.15 * (dependents == "Yes") + 0.012 * (monthly - 65.0))
    churn = _yes(rng, 1.0 / (1.0 + math.exp(-score)))
    return {
        "customerID": f"{prefix}-{index:06d}", "gender": gender, "SeniorCitizen": senior, "Partner": partner,
        "Dependents": dependents, "tenure": tenure, "PhoneService": phone, "InternetService": internet,
        "Contract": contract, "PaperlessBilling": paperless, "PaymentMethod": payment,
        "MonthlyCharges": f"{monthly:.2f}", "TotalCharges": total, "Churn": churn,
    }


GENERATORS = {"telco-churn": {"columns": TELCO_COLUMNS, "target": "Churn", "row": _telco, "version": "telco-churn/v1"}}


def validate_synthetic(dataset: dict) -> dict:
    """Structural checks for dataset.synthetic; only mapped lake scenarios may declare it."""
    value = dataset.get("synthetic")
    if dataset.get("provider") != "lake":
        raise ValueError("Synthetic datasets must use provider 'lake'; they are never downloaded")
    if not isinstance(value, dict) or set(value) != {"generator", "seed", "rows"}:
        raise ValueError("dataset.synthetic needs exactly the fields generator, seed and rows")
    if value["generator"] not in GENERATORS:
        raise ValueError(f"Unknown synthetic generator {value['generator']!r}; choose from {sorted(GENERATORS)}")
    if type(value["seed"]) is not int or value["seed"] < 0:
        raise ValueError("dataset.synthetic.seed must be a non-negative integer")
    if type(value["rows"]) is not int or not 100 <= value["rows"] <= 1_000_000:
        raise ValueError("dataset.synthetic.rows must be an integer from 100 to 1000000")
    if not dataset.get("file") or Path(dataset["file"]).name != dataset["file"] or not dataset["file"].endswith(".csv"):
        raise ValueError("Synthetic datasets need a single .csv dataset.file name")
    return value


def _generator(scenario: dict) -> tuple[dict, dict]:
    settings = validate_synthetic(scenario["dataset"])
    generator = GENERATORS[settings["generator"]]
    if scenario.get("target") != generator["target"]:
        raise ValueError(f"Generator {settings['generator']} produces target {generator['target']!r}")
    missing = set(scenario.get("features", [])) - set(generator["columns"])
    if missing:
        raise ValueError(f"Generator {settings['generator']} does not produce features {sorted(missing)}")
    return settings, generator


def _csv(rows, columns) -> bytes:
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=list(columns), lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return buffer.getvalue().encode("utf-8")


def generate(scenario: dict, output: Path) -> dict:
    """Write `dataset.file` and provenance.json once; identical reruns are reported as unchanged."""
    settings, generator = _generator(scenario)
    dataset = scenario["dataset"]
    rng = random.Random(settings["seed"])
    rows = [generator["row"](rng, index, "SYN") for index in range(1, settings["rows"] + 1)]
    content = _csv(rows, generator["columns"])
    digest = hashlib.sha256(content).hexdigest()
    provenance = {
        "provider": "lake", "kind": dataset.get("kind", "dataset"), "version": dataset.get("version", 1),
        "license": LICENSE, "synthetic": dict(settings), "generator_version": generator["version"],
        "files": {dataset["file"]: digest}, "created_by": "ml_model_factory.synthetic",
    }
    output = Path(output)
    target, record = output / dataset["file"], output / "provenance.json"
    if target.exists() or record.exists():
        if (not target.is_file() or hashlib.sha256(target.read_bytes()).hexdigest() != digest
                or not record.is_file() or load_json(record) != provenance):
            raise ValueError(f"Existing synthetic output in {output} differs; choose a new folder or version")
        status = "unchanged"
    else:
        output.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
        write_json(record, provenance)
        status = "created"
    return {"file": str(target), "rows": len(rows), "sha256": digest, "provenance": str(record), "status": status}


def generate_requests(scenario: dict, output: Path, *, rows: int = 50, seed: int | None = None) -> dict:
    """Unlabeled scoring requests with request_id and only the model's feature columns."""
    import pandas as pd

    settings, generator = _generator(scenario)
    if type(rows) is not int or not 1 <= rows <= 10_000:
        raise ValueError("Request rows must be an integer from 1 to 10000")
    seed = settings["seed"] + 1 if seed is None else seed
    if type(seed) is not int or seed < 0 or seed == settings["seed"]:
        raise ValueError("Requests need their own non-negative seed, different from the training seed")
    rng = random.Random(seed)
    records = [generator["row"](rng, index, "REQ") for index in range(1, rows + 1)]
    frame = pd.DataFrame(records)
    frame.insert(0, "request_id", [f"req-{seed}-{index:05d}" for index in range(1, rows + 1)])
    frame = frame.loc[:, ["request_id", *scenario["features"]]]
    for column in frame.columns:
        if column in ("SeniorCitizen", "tenure"):
            frame[column] = frame[column].astype("int64")
        elif column in ("MonthlyCharges",):
            frame[column] = frame[column].astype("float64")
    output = Path(output)
    if (output / "requests.parquet").exists():
        raise ValueError(f"Requests already exist in {output}; choose a new folder")
    output.mkdir(parents=True, exist_ok=True)
    frame.to_parquet(output / "requests.parquet", index=False)
    write_json(output / "manifest.json", {"rows": rows, "seed": seed, "generator": settings["generator"],
                                          "columns": list(frame.columns), "labels_included": False,
                                          "request_id_column": "request_id"})
    return {"requests": str(output / "requests.parquet"), "rows": rows, "seed": seed}


def _synthesize_command(args):
    from .config import validate_scenario

    return generate(validate_scenario(load_json(args.scenario)), args.output)


def add_commands(commands) -> None:
    synthesize = commands.add_parser("synthesize", help="Generate a scenario's deterministic synthetic source locally")
    synthesize.add_argument("--scenario", required=True, type=Path)
    synthesize.add_argument("--output", required=True, type=Path)
    synthesize.set_defaults(handler=_synthesize_command)
