"""The two allowlisted use cases and the M49 telco-churn project copy."""
from __future__ import annotations

from copy import deepcopy

from . import NAME

CHURN = NAME
AIR = "air-passengers"
DATA_FILE = "telco-churn-synthetic.csv"
DATA_VERSION_PREFIX = "aif49-synth-v"
CHURN_LEAF = "usecase-type/batch/classification/azureml-pipeline"
AIR_LEAF = "usecase-type/batch/timeseries-forecasting/azureml-pipeline"
RUN_KEY = "custom-pipeline"

USECASES = {
    CHURN: {"model_number": 49, "task": "classification", "mode": "custom", "operation": "create",
            "leaf": CHURN_LEAF, "synthetic": True},
    AIR: {"model_number": 5, "task": "forecasting", "mode": "custom", "operation": "retrain",
          "leaf": AIR_LEAF, "synthetic": False},
}
OPERATIONS = {
    CHURN: ("create-usecase", "train", "infer"),
    AIR: ("retrain", "infer"),
}


def usecase(name: str) -> dict:
    if name not in USECASES:
        raise ValueError(f"Unknown use case {name!r}; allowed: {', '.join(USECASES)}")
    return deepcopy(USECASES[name])


def alias(name: str) -> str:
    return f"M{usecase(name)['model_number']:02d}"


def model_name(name: str) -> str:
    """The registered Azure ML model name that esml-v2 derives from the scenario name."""
    return f"{alias(name)}_{name.replace('-', '_')}"


def expected_names(name: str) -> dict:
    """Model-prefix names produced by azure_esml ESMLNaming for a single-dataset use case."""
    prefix = f"{alias(name)}_{name}"
    return {
        "input_data_asset": f"{prefix}_in",
        "gold_train_data_asset": f"{prefix}_gold_train",
        "training_experiment": f"{prefix}_IN_2_GOLD_TRAINING_MANUAL",
        "inference_experiment": f"{prefix}_GOLD_INFERENCE",
        "model": model_name(name),
    }


def churn_scenario(template: dict) -> dict:
    """Copy the factory churn template's model contract onto a synthetic, lake-backed source.

    Only features, target, split, budgets and quality gates are reused. The template's
    third-party dataset reference is never copied, so no license-gated data can be used.
    """
    if template.get("name") != "churn" or template.get("task") != "classification":
        raise ValueError("Expected the factory churn classification template")
    scenario = {
        "name": CHURN,
        "task": "classification",
        "model_name": "telco-churn-synthetic",
        "dataset": {
            "provider": "lake", "kind": "dataset", "file": DATA_FILE, "version": 1,
            "license": "Synthetic data generated by ml_model_factory.synthetic; no third-party data",
            "status": "configured",
            "synthetic": {"generator": "telco-churn", "seed": 49, "rows": 7043},
            "notes": ("Deterministic synthetic telco churn data with the template's columns. Regenerate it "
                      "with `python -m ml_model_factory synthesize`; no download or license review is needed."),
        },
        "example_leaves": [CHURN_LEAF],
    }
    for key in ("features", "target", "categorical_features", "sensitive_features", "split", "automl",
                "custom", "quality"):
        if key in template:
            scenario[key] = deepcopy(template[key])
    return scenario
